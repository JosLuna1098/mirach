def test_lang_with_yes_changes_voice_on_mismatch(tmp_path, monkeypatch):
    """--yes auto-accepts the voice change when voice lang != target lang."""
    downloaded: list[str] = []
    monkeypatch.setattr("mirach.cli._systemd_unit_active", lambda: False)
    monkeypatch.setattr(
        "mirach.cli._download_voice",
        lambda name, url, d: downloaded.append(name),
    )

    f = tmp_path / "mirach.env"
    # Pre-set an English voice so there's a mismatch when switching to es
    set_env_vars({"MIRACH_VOICE": "en_US-lessac-low.onnx"}, f)

    rc = main(["--env-file", str(f), "lang", "es", "--yes"])
    assert rc == 0

    env = read_env(f)
    assert env["MIRACH_VOICE"] == pack_for("es")["voice"]
    assert len(downloaded) == 1


def test_lang_voice_mismatch_detection():
    """Voice lang heuristic correctly identifies mismatch."""
    assert _voice_lang("en_US-lessac-low.onnx") != "es"
    assert _voice_lang("es_MX-ald-medium.onnx") != "en"


def test_lang_no_change_when_voice_already_matches(tmp_path, monkeypatch):
    """No voice download when voice already matches target language."""
    downloaded: list[str] = []
    monkeypatch.setattr("mirach.cli._systemd_unit_active", lambda: False)
    monkeypatch.setattr(
        "mirach.cli._download_voice",
        lambda name, url, d: downloaded.append(name),
    )

    f = tmp_path / "mirach.env"
    # Pre-set a Spanish voice — no mismatch when switching to es
    set_env_vars({"MIRACH_VOICE": "es_MX-ald-medium.onnx"}, f)

    rc = main(["--env-file", str(f), "lang", "es", "--yes"])
    assert rc == 0
    assert downloaded == []


def test_lang_all_packs_have_required_keys():
    """Regression: every language pack provides the 3 keys the CLI writes."""
    for code in LANGUAGE_PACKS:
        pack = pack_for(code)
        assert "locale" in pack
        assert "whisper_model" in pack
        assert "whisper_lang" in pack
