"""Tests for mirach/cli.py — env helper round-trips and lang subcommand.

These tests do NOT import sounddevice and do NOT touch the real mirach.env.
All env I/O uses a tmp_path fixture.  systemd and voice downloads are mocked.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from mirach.cli import _voice_lang, main, read_env, set_env_vars
from mirach.langpack import LANGUAGE_PACKS, pack_for

# ── read_env / set_env_vars ────────────────────────────────────────────────────


def test_read_env_nonexistent_returns_empty(tmp_path):
    assert read_env(tmp_path / "missing.env") == {}


def test_read_env_basic(tmp_path):
    f = tmp_path / "mirach.env"
    f.write_text("MIRACH_LOCALE=es\nMIRACH_WHISPER_MODEL=medium\n")
    env = read_env(f)
    assert env["MIRACH_LOCALE"] == "es"
    assert env["MIRACH_WHISPER_MODEL"] == "medium"


def test_read_env_ignores_comments_and_blanks(tmp_path):
    f = tmp_path / "mirach.env"
    f.write_text("# a comment\n\nMIRACH_LOCALE=en\n# another\n")
    env = read_env(f)
    assert list(env.keys()) == ["MIRACH_LOCALE"]


def test_read_env_splits_on_first_equals(tmp_path):
    f = tmp_path / "mirach.env"
    f.write_text("MIRACH_VOICE_URL=https://host/path?a=1&b=2\n")
    env = read_env(f)
    assert env["MIRACH_VOICE_URL"] == "https://host/path?a=1&b=2"


def test_set_env_vars_creates_file_with_header(tmp_path):
    f = tmp_path / "new.env"
    set_env_vars({"MIRACH_LOCALE": "es"}, f)
    text = f.read_text()
    assert "MIRACH_LOCALE=es" in text
    assert text.startswith("#")  # has header comment


def test_set_env_vars_upsert_existing_key(tmp_path):
    f = tmp_path / "mirach.env"
    f.write_text("# comment\nMIRACH_LOCALE=en\nMIRACH_HOTKEY=Alt+Z\n")
    set_env_vars({"MIRACH_LOCALE": "es"}, f)
    env = read_env(f)
    assert env["MIRACH_LOCALE"] == "es"
    assert env["MIRACH_HOTKEY"] == "Alt+Z"


def test_set_env_vars_appends_new_key(tmp_path):
    f = tmp_path / "mirach.env"
    f.write_text("MIRACH_LOCALE=en\n")
    set_env_vars({"MIRACH_VOICE": "es_MX-ald-medium.onnx"}, f)
    env = read_env(f)
    assert env["MIRACH_LOCALE"] == "en"
    assert env["MIRACH_VOICE"] == "es_MX-ald-medium.onnx"


def test_set_env_vars_preserves_comments(tmp_path):
    f = tmp_path / "mirach.env"
    f.write_text("# Generated by install.py\n# See mirach.env.example\n\nMIRACH_LOCALE=en\n")
    set_env_vars({"MIRACH_LOCALE": "es"}, f)
    text = f.read_text()
    assert "# Generated by install.py" in text
    assert "# See mirach.env.example" in text


def test_set_env_vars_idempotent(tmp_path):
    f = tmp_path / "mirach.env"
    f.write_text("MIRACH_LOCALE=es\n")
    set_env_vars({"MIRACH_LOCALE": "es"}, f)
    set_env_vars({"MIRACH_LOCALE": "es"}, f)
    lines = [ln for ln in f.read_text().splitlines() if ln.startswith("MIRACH_LOCALE=")]
    assert len(lines) == 1


def test_round_trip(tmp_path):
    f = tmp_path / "mirach.env"
    data = {"MIRACH_LOCALE": "es", "MIRACH_WHISPER_MODEL": "medium", "MIRACH_HOTKEY": "Alt+Z"}
    set_env_vars(data, f)
    assert read_env(f) == data


