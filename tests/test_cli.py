def _run_lang(tmp_env: Path, code: str, extra: list[str] | None = None, monkeypatch=None) -> int:
    """Run main(['lang', code]) pointing at a temp env file, with mocked systemd/download."""
    argv = ["--env-file", str(tmp_env), "lang", code] + (extra or [])
    return main(argv)


